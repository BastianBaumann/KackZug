"""Builds the Android launcher icon and the Avalonia logo resource from assets/logo/kackzug.svg.

Only the small SVG subset used by the logo is supported: g (translate, clip-path, inherited
fill/stroke), path, rect (with rx), circle and line.

Usage: python tools/logo/build_icons.py
"""

import pathlib
import re
import xml.etree.ElementTree as ElementTree

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "assets" / "logo" / "kackzug.svg"
ANDROID_RESOURCES = ROOT / "src" / "KackZug.Android" / "Resources"
AVALONIA_RESOURCE = ROOT / "src" / "KackZug.App" / "Assets" / "Logo.axaml"

SVG_NAMESPACE = "{http://www.w3.org/2000/svg}"
ICON_BACKGROUND = "#FFF3DC"
INHERITED = ("fill", "stroke", "stroke-width", "stroke-linejoin", "stroke-linecap")


def number(value):
    return float(value)


def format_number(value):
    text = ("%.2f" % value).rstrip("0").rstrip(".")
    if text == "-0":
        return "0"
    return text


def rect_path(element):
    x = number(element.get("x"))
    y = number(element.get("y"))
    width = number(element.get("width"))
    height = number(element.get("height"))
    radius = number(element.get("rx", "0"))
    if radius <= 0:
        return "M%s,%s h%s v%s h%s Z" % tuple(format_number(v) for v in (x, y, width, height, -width))
    inner_width = width - 2 * radius
    inner_height = height - 2 * radius
    r = format_number(radius)
    parts = [
        "M%s,%s" % (format_number(x + radius), format_number(y)),
        "h%s" % format_number(inner_width),
        "a%s,%s 0 0 1 %s,%s" % (r, r, r, r),
        "v%s" % format_number(inner_height),
        "a%s,%s 0 0 1 -%s,%s" % (r, r, r, r),
        "h%s" % format_number(-inner_width),
        "a%s,%s 0 0 1 -%s,-%s" % (r, r, r, r),
        "v%s" % format_number(-inner_height),
        "a%s,%s 0 0 1 %s,-%s" % (r, r, r, r),
        "Z",
    ]
    return " ".join(parts)


def circle_path(element):
    cx = number(element.get("cx"))
    cy = number(element.get("cy"))
    radius = number(element.get("r"))
    r = format_number(radius)
    start = "M%s,%s" % (format_number(cx - radius), format_number(cy))
    first = "a%s,%s 0 1 0 %s,0" % (r, r, format_number(2 * radius))
    second = "a%s,%s 0 1 0 %s,0" % (r, r, format_number(-2 * radius))
    return start + " " + first + " " + second + " Z"


def line_path(element):
    values = [number(element.get(name)) for name in ("x1", "y1", "x2", "y2")]
    return "M%s,%s L%s,%s" % tuple(format_number(v) for v in values)


def element_path(element, tag):
    if tag == "path":
        return element.get("d")
    if tag == "rect":
        return rect_path(element)
    if tag == "circle":
        return circle_path(element)
    if tag == "line":
        return line_path(element)
    return None


def collect(element, style, clip_paths, shapes):
    tag = element.tag.replace(SVG_NAMESPACE, "")
    if tag in ("defs", "title", "clipPath"):
        return
    own_style = dict(style)
    for name in INHERITED:
        if element.get(name) is not None:
            own_style[name] = element.get(name)
    clip = element.get("clip-path")
    if clip is not None:
        clip_id = re.search(r"url\(#(.+)\)", clip).group(1)
        own_style["clip"] = clip_paths[clip_id]
    translate = element.get("transform")
    if translate is not None:
        match = re.match(r"translate\(([-\d.]+),([-\d.]+)\)", translate)
        own_style["dx"] = style.get("dx", 0.0) + number(match.group(1))
        own_style["dy"] = style.get("dy", 0.0) + number(match.group(2))
    if tag == "line":
        own_style["fill"] = "none"
    path = element_path(element, tag)
    if path is not None:
        shapes.append((path, own_style))
        return
    for child in element:
        collect(child, own_style, clip_paths, shapes)


def read_shapes():
    tree = ElementTree.parse(SOURCE)
    root = tree.getroot()
    clip_paths = {}
    for clip in root.iter(SVG_NAMESPACE + "clipPath"):
        path = clip.find(SVG_NAMESPACE + "path")
        clip_paths[clip.get("id")] = path.get("d")
    shapes = []
    collect(root, {"dx": 0.0, "dy": 0.0}, clip_paths, shapes)
    return shapes


def android_color(value):
    return "#FF" + value.lstrip("#").upper()


def build_android(shapes):
    scale = 0.155
    offset = (108 - 512 * scale) / 2
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by tools/logo/build_icons.py from assets/logo/kackzug.svg -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="108dp" android:height="108dp"',
        '    android:viewportWidth="108" android:viewportHeight="108">',
        '  <group android:translateX="%s" android:translateY="%s" android:scaleX="%s" android:scaleY="%s">'
        % (format_number(offset), format_number(offset), scale, scale),
    ]
    for path, style in shapes:
        group_open = '    <group android:translateX="%s" android:translateY="%s">' % (
            format_number(style["dx"]), format_number(style["dy"]))
        lines.append(group_open)
        if "clip" in style:
            lines.append('      <clip-path android:pathData="%s" />' % style["clip"])
        attributes = ['android:pathData="%s"' % path]
        fill = style.get("fill", "#000000")
        if fill != "none":
            attributes.append('android:fillColor="%s"' % android_color(fill))
        stroke = style.get("stroke")
        if stroke is not None and (fill == "none" or "stroke-width" in style):
            attributes.append('android:strokeColor="%s"' % android_color(stroke))
            attributes.append('android:strokeWidth="%s"' % style.get("stroke-width", "1"))
            attributes.append('android:strokeLineJoin="round"')
            attributes.append('android:strokeLineCap="round"')
        lines.append("      <path " + " ".join(attributes) + " />")
        lines.append("    </group>")
    lines.append("  </group>")
    lines.append("</vector>")
    foreground = ANDROID_RESOURCES / "drawable" / "icon_foreground.xml"
    foreground.write_text("\n".join(lines) + "\n", encoding="utf-8")

    adaptive = "\n".join([
        '<?xml version="1.0" encoding="utf-8"?>',
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">',
        '  <background android:drawable="@color/icon_background" />',
        '  <foreground android:drawable="@drawable/icon_foreground" />',
        '  <monochrome android:drawable="@drawable/icon_foreground" />',
        "</adaptive-icon>",
    ])
    mipmap = ANDROID_RESOURCES / "mipmap-anydpi-v26"
    mipmap.mkdir(exist_ok=True)
    (mipmap / "icon.xml").write_text(adaptive + "\n", encoding="utf-8")

    colors = "\n".join([
        '<?xml version="1.0" encoding="utf-8"?>',
        "<resources>",
        '  <color name="icon_background">%s</color>' % ICON_BACKGROUND,
        "</resources>",
    ])
    (ANDROID_RESOURCES / "values" / "icon_colors.xml").write_text(colors + "\n", encoding="utf-8")


def build_avalonia(shapes):
    lines = [
        '<ResourceDictionary xmlns="https://github.com/avaloniaui"',
        '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
        "    <!-- Generated by tools/logo/build_icons.py from assets/logo/kackzug.svg -->",
        '    <DrawingImage x:Key="LogoImage">',
        "        <DrawingGroup>",
        '            <GeometryDrawing Brush="Transparent" Geometry="M0,0 H512 V512 H0 Z" />',
    ]
    for path, style in shapes:
        group = "            <DrawingGroup"
        if "clip" in style:
            group += ' ClipGeometry="%s"' % style["clip"]
        lines.append(group + ">")
        lines.append("                <DrawingGroup.Transform>")
        lines.append('                    <TranslateTransform X="%s" Y="%s" />'
                     % (format_number(style["dx"]), format_number(style["dy"])))
        lines.append("                </DrawingGroup.Transform>")
        drawing = '                <GeometryDrawing Geometry="%s"' % path
        fill = style.get("fill", "#000000")
        if fill != "none":
            drawing += ' Brush="%s"' % fill
        stroke = style.get("stroke")
        if stroke is not None and (fill == "none" or "stroke-width" in style):
            lines.append(drawing + ">")
            lines.append("                    <GeometryDrawing.Pen>")
            lines.append('                        <Pen Brush="%s" Thickness="%s" LineJoin="Round" LineCap="Round" />'
                         % (stroke, style.get("stroke-width", "1")))
            lines.append("                    </GeometryDrawing.Pen>")
            lines.append("                </GeometryDrawing>")
        else:
            lines.append(drawing + " />")
        lines.append("            </DrawingGroup>")
    lines.append("        </DrawingGroup>")
    lines.append("    </DrawingImage>")
    lines.append("</ResourceDictionary>")
    AVALONIA_RESOURCE.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    shapes = read_shapes()
    build_android(shapes)
    build_avalonia(shapes)
    print("%d shapes written" % len(shapes))


if __name__ == "__main__":
    main()
